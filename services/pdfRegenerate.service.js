// Company review decisions that issue the Notice of Acceptance
const COMPANY_ACCEPT_DECISIONS = ["Approved", "Approved With Conditions", "Completed"];

const companySet = async (id) => {
  const { NewCompanyRegistration, NewCompanyPdf } = require("../models");
  const record = await NewCompanyRegistration.findByPk(id, { include: COMPANY_REVIEW_INCLUDES });
  if (!record) return null;
  const { sanitizeName } = require("./newCompanyPdf.service");
  const history = await NewCompanyPdf.findAll({ where: { registrationId: id }, order: [["id", "ASC"]] });
  const latestPath = (type, personName) =>
    [...history].reverse().find((h) => h.type === type && (personName ? h.personName === personName : true))?.filePath || null;
  const items = [];

  items.push({ key: "ClientApplication", type: "ClientApplication", label: "Client Application", file: "Client_Application", column: "clientPdfPath", stage: "submission", relPath: record.clientPdfPath || null });
  (record.officeholders || [])
    .filter((oh) => oh.consentAccepted)
    .forEach((oh) =>
      items.push({ key: `DirectorConsent:${oh.id}`, type: "DirectorConsent", label: `Director Consent - ${oh.fullName}`, file: `Director_Consent_${sanitizeName(oh.fullName)}`, personName: oh.fullName, person: oh, extraKey: "officeholder", stage: "submission", relPath: latestPath("DirectorConsent", oh.fullName) })
    );
  (record.shareholders || [])
    .filter((sh) => sh.consentAccepted)
    .forEach((sh) =>
      items.push({ key: `MemberConsent:${sh.id}`, type: "MemberConsent", label: `Member Consent - ${sh.fullName}`, file: `Member_Consent_${sanitizeName(sh.fullName)}`, personName: sh.fullName, person: sh, extraKey: "shareholder", stage: "submission", relPath: latestPath("MemberConsent", sh.fullName) })
    );
  if (record.adminPdfPath || record.adminReview || history.some((h) => h.type === "AdminReview")) {
    items.push({ key: "AdminReview", type: "AdminReview", label: "Admin Compliance Review", file: "Admin_Compliance_Review", column: "adminPdfPath", stage: "decision", relPath: record.adminPdfPath || null });
  }
  if (record.acceptancePdfPath || COMPANY_ACCEPT_DECISIONS.includes(record.adminReview?.reviewStatus) || history.some((h) => h.type === "Acceptance")) {
    items.push({ key: "Acceptance", type: "Acceptance", label: "Notice of Acceptance", file: "Acceptance", column: "acceptancePdfPath", stage: "decision", relPath: record.acceptancePdfPath || null });
  }

  items.forEach((item) => {
    item.present = present(item.relPath);
    item.history = history.filter((h) => h.type === item.type && (item.personName ? h.personName === item.personName : true));
  });
  return { record, items, title: record.referenceNumber };
};

const rebuildCompany = async (record, item, actorName) => {
  const { generateCompanyPdf } = require("./newCompanyPdf.service");
  const { NewCompanyRegistration } = require("../models");
  const latest = item.history[item.history.length - 1] || null;
  const snapshot = parseSnapshot(latest?.snapshot);
  let data;
  let extra;
  let asOf;
  let settings;

  if (snapshot) {
    ({ data, extra, asOf, settings } = snapshot);
  } else {
    const source = item.stage === "submission" ? item.history[0] || latest : latest;
    // Same included data as the original generation
    const loaded = await NewCompanyRegistration.findByPk(record.id, {
      include: item.stage === "submission" ? COMPANY_SUBMISSION_INCLUDES : COMPANY_REVIEW_INCLUDES,
    });
    const full = plain(loaded);
    asOf = new Date(source?.generatedAt || (item.stage === "submission" ? full.submittedAt || full.createdAt : full.adminReview?.updatedAt || full.updatedAt)).toISOString();
    const status = item.stage === "submission" ? "Submitted" : await realStatus("new-company", record);
    data = asAt(full, asOf, { status });
    extra = item.extraKey ? { [item.extraKey]: plain(item.person) } : {};
    settings = await getSettingsMap();
  }

  return generateCompanyPdf(item.type, item.file, data, extra, item.personName || null, {
    asOf,
    settings,
    targetRelPath: item.relPath,
    generatedBy: item.personName ? item.personName : `Regenerated by ${actorName}`,
    version: latest?.version,
  });
};

