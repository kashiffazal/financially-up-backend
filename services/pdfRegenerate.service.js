/**
 * Regenerate PDFs (Individual Engagement + Company Registration)
 * ==============================================================
 * Rebuilds an application's PDFs when a file was deleted from the server, is
 * damaged or blank. The rebuilt file is identical to the original (only the
 * PDF's hidden internal creation time differs):
 *
 *   - PDFs made since snapshots exist: the exact inputs are replayed
 *     (data, company settings, date - new_*_pdfs.snapshot).
 *   - Older PDFs: the application is rebuilt as it was at that moment - the
 *     original generation date, only the rows that existed then (review, audit
 *     entries, signatures...), the status it had, and the same included data
 *     the original was made with.
 *
 * The file is written back to the exact link the record already has, so admin
 * links keep working; the PDF history gets "Regenerated by <name>" with the same
 * version number. Nothing is emailed.
 */

const { diskPathOfUpload } = require("../utils/privateFiles");
const { parseSnapshot } = require("./pdfEngine");
const { getSettingsMap } = require("./settings.service");

const MODULES = ["new-individual", "new-company"];

// Included data, exactly as the original generations loaded it
const INDIVIDUAL_INCLUDES = ["client", "services", "identity", "documents", "consents", "signatures", "auditLogs", "adminReview"];
const COMPANY_SUBMISSION_INCLUDES = ["officeholders", "shareholders", "beneficialOwners", "documents"];
const COMPANY_REVIEW_INCLUDES = [...COMPANY_SUBMISSION_INCLUDES, "adminReview"];

const ACCEPT_DECISIONS = ["Accept", "Accepted", "Conditional Accept"];

const present = (relPath) => Boolean(relPath && diskPathOfUpload(relPath));
const plain = (record) => (record && typeof record.toJSON === "function" ? record.toJSON() : record);

/** Status the record had before it went to Trash (Trash is never printed on a PDF). */
const realStatus = async (moduleKey, record) => {
  if (record.status !== "Trash") return record.status;
  const { RecordTrash } = require("../models");
  const saved = await RecordTrash.findOne({ where: { moduleKey, recordId: record.id } });
  return saved?.previousStatus || null;
};

/**
 * The application as it was at `asOf`: rows created later are left out (review,
 * audit entries, signatures, documents...), and the status is the one it had.
 */
const asAt = (data, asOf, { status, reviewKey = "adminReview" } = {}) => {
  const limit = new Date(asOf).getTime() + 1000;
  const existed = (row) => !row?.createdAt || new Date(row.createdAt).getTime() <= limit;
  const copy = { ...data };
  Object.keys(copy).forEach((key) => {
    if (Array.isArray(copy[key])) copy[key] = copy[key].filter(existed);
  });
  if (copy[reviewKey] && !existed(copy[reviewKey])) copy[reviewKey] = null;
  if (status) copy.status = status;
  return copy;
};

// ---------------------------------------------------------------------------
// Individual Engagement
// ---------------------------------------------------------------------------
const INDIVIDUAL_PDFS = [
  { type: "ClientEngagement", label: "Client Engagement", file: "Client_Engagement", column: "clientPdfPath", stage: "submission" },
  { type: "AdminReview", label: "Admin Review", file: "Admin_Review", column: "adminPdfPath", stage: "submission" },
  { type: "EngagementAcceptance", label: "Engagement Acceptance", file: "Engagement_Acceptance", column: "acceptancePdfPath", stage: "decision" },
  { type: "AuditReport", label: "Audit Report", file: "Audit_Report", column: "auditPdfPath", stage: "decision" },
];

const individualSet = async (id) => {
  const { NewIndividualEngagement, NewIndividualPdf } = require("../models");
  const record = await NewIndividualEngagement.findByPk(id, { include: INDIVIDUAL_INCLUDES });
  if (!record) return null;
  const history = await NewIndividualPdf.findAll({ where: { engagementId: id }, order: [["id", "ASC"]] });
  const review = record.adminReview;
  const items = INDIVIDUAL_PDFS.filter((pdf) => {
    if (pdf.stage === "submission") return true;
    // Decision PDFs: when there is one (or there was a decision that makes it)
    if (record[pdf.column] || history.some((h) => h.type === pdf.type)) return true;
    if (pdf.type === "EngagementAcceptance") return Boolean(review && ACCEPT_DECISIONS.includes(review.decision));
    return Boolean(review);
  }).map((pdf) => ({
    key: pdf.type,
    ...pdf,
    relPath: record[pdf.column] || null,
    present: present(record[pdf.column]),
    history: history.filter((h) => h.type === pdf.type),
  }));
  return { record, items, title: record.referenceNumber };
};

const rebuildIndividual = async (record, item, actorName) => {
  const { generateIndividualPdf } = require("./individualPdf.service");
  const latest = item.history[item.history.length - 1] || null;
  const snapshot = parseSnapshot(latest?.snapshot);
  let data;
  let extra;
  let asOf;
  let settings;

  if (snapshot) {
    ({ data, extra, asOf, settings } = snapshot);
  } else {
    const full = plain(record);
    // The client engagement is from the submission; the others from the latest generation
    const source = item.type === "ClientEngagement" ? item.history[0] : latest;
    asOf = (source?.generatedAt || (item.stage === "submission" ? full.submittedAt || full.createdAt : full.adminReview?.updatedAt) || new Date()).toISOString?.()
      || new Date(source?.generatedAt || full.createdAt).toISOString();
    asOf = new Date(asOf).toISOString();
    const reviewThen = full.adminReview && new Date(full.adminReview.createdAt).getTime() <= new Date(asOf).getTime() + 1000;
    const status = item.type === "ClientEngagement" || !reviewThen ? "Pending Review" : await realStatus("new-individual", record);
    data = asAt(full, asOf, { status });
    // Decision-time PDFs were made with the reviewer's name
    if (reviewThen && item.type !== "ClientEngagement") data.taxAgentName = full.adminReview.reviewerName;
    const staff = latest?.generatedBy || full.adminReview?.reviewerName;
    extra =
      item.type === "EngagementAcceptance"
        ? { staffName: staff }
        : item.type === "AuditReport"
          ? { auditorName: staff || "Compliance Auditor" }
          : {};
    settings = await getSettingsMap();
  }

  return generateIndividualPdf(item.type, item.file, data, extra, {
    asOf,
    settings,
    targetRelPath: item.relPath,
    generatedBy: `Regenerated by ${actorName}`,
    version: latest?.version,
  });
};

