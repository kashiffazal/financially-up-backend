/** The PDFs an application should have, each Present / Missing. */
const listPdfs = async (moduleKey, id) => {
  const set = moduleKey === "new-individual" ? await individualSet(id) : await companySet(id);
  if (!set) return null;
  return {
    reference: set.title,
    pdfs: set.items.map(({ key, label, present: isPresent, relPath }) => ({ key, label, present: isPresent, hasLink: Boolean(relPath) })),
  };
};

/**
 * Rebuild the PDFs of the application: all of them, or only the keys in `only`
 * (e.g. ["Acceptance"] - "Rebuild missing only"). Unknown keys are ignored.
 * @param {string[]|null} [only]
 * @returns {{ reference, results: { key, label, ok, replaced, message }[] }}
 */
const regenerateAll = async (moduleKey, id, actorName, only = null) => {
  const set = moduleKey === "new-individual" ? await individualSet(id) : await companySet(id);
  if (!set) return null;
  const wanted = Array.isArray(only) && only.length ? new Set(only.map(String)) : null;
  const items = wanted ? set.items.filter((item) => wanted.has(item.key)) : set.items;
  const results = [];
  for (const item of items) {
    let relPath = null;
    try {
      relPath =
        moduleKey === "new-individual" ? await rebuildIndividual(set.record, item, actorName) : await rebuildCompany(set.record, item, actorName);
    } catch (error) {
      console.error(`[PDF] Regenerate ${moduleKey} #${id} ${item.type} failed:`, error);
    }
    // A PDF that had no link yet gets the new one
    if (relPath && item.column && set.record[item.column] !== relPath) await set.record.update({ [item.column]: relPath });
    results.push({
      key: item.key,
      label: item.label,
      ok: Boolean(relPath),
      replaced: item.present,
      message: relPath ? (item.present ? "Replaced" : "Rebuilt") : "Not generated - the PDF service did not respond. Try again.",
    });
  }
  return { reference: set.title, results };
};

/**
 * How many of an application's main PDFs are missing (for the "PDF missing" marker
 * in the logs; a quick file check, consent PDFs are only counted in listPdfs).
 * @param {object} row - plain record with its adminReview
 */
const missingPdfCount = (moduleKey, row) => {
  const review = row.adminReview;
  const expected =
    moduleKey === "new-individual"
      ? [
          row.clientPdfPath || "",
          row.adminPdfPath || "",
          ...(row.acceptancePdfPath || (review && ACCEPT_DECISIONS.includes(review.decision)) ? [row.acceptancePdfPath || ""] : []),
          ...(row.auditPdfPath || review ? [row.auditPdfPath || ""] : []),
        ]
      : [
          row.clientPdfPath || "",
          ...(row.adminPdfPath || review ? [row.adminPdfPath || ""] : []),
          ...(row.acceptancePdfPath || COMPANY_ACCEPT_DECISIONS.includes(review?.reviewStatus) ? [row.acceptancePdfPath || ""] : []),
        ];
  return expected.filter((relPath) => !present(relPath)).length;
};

module.exports = { MODULES, listPdfs, regenerateAll, asAt, missingPdfCount, COMPANY_ACCEPT_DECISIONS };
